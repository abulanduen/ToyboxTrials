export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Horizontal advance per character (glyph + one pixel of space). */
export const ADVANCE = GLYPH_W + 1;

const ROWS = new Map<string, string[]>(Object.entries(G).map(([k, v]) => [k, v.split('|')]));

/** The glyph rows for a character ('#' = lit), upper-casing letters; unknown characters become '?'. */
export function glyph(ch: string): string[] {
  const c = ch === '–' || ch === '—' ? '-' : ch.toUpperCase();
  return ROWS.get(c) ?? ROWS.get('?')!;
}

/** Width in pixels of `text` at `scale`. */
export const textWidth = (text: string, scale = 1) => Math.max(0, text.length * ADVANCE - 1) * scale;

/** Word-wrap `text` into lines of at most `max` characters (long words are cut). */
export function wrap(text: string, max: number): string[] {
  const out: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/).filter(Boolean)) {
    let w = word;
    while (w.length > max) {
      if (line) {
        out.push(line);
        line = '';
      }
      out.push(w.slice(0, max));
      w = w.slice(max);
    }
    if (!line) line = w;
    else if (line.length + 1 + w.length <= max) line += ' ' + w;
    else {
      out.push(line);
      line = w;
    }
  }
  if (line) out.push(line);
  return out;
}

/** Draw `text` with its top-left at (x, y), each font pixel a `scale` × `scale` square. */
export function drawPixelText(g: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string) {
  g.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    const rows = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++) for (let c = 0; c < GLYPH_W; c++) if (rows[r][c] === '#') g.fillRect(cx + c * scale, y + r * scale, scale, scale);
    cx += ADVANCE * scale;
  }
}
