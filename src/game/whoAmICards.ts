/**
 * Who Am I? cards: everyday things (animals, jobs, foods, objects) the jack slaps on a player's
 * face at the suspicious box in the online Hub. Shared by the server (which deals them) and the
 * client (nothing here is secret: the server never tells a holder which card they wear).
 *
 * Every entry is a plain, generic noun: no brands, no famous or copyrighted characters.
 * `also` lists extra accepted answers (synonyms, other spellings, irregular plurals); regular
 * plurals, "a/an/the" and spacing are handled by src/game/whoAmI.ts. `art` overrides the
 * article used in announcements ("an umbrella", "scissors").
 */
export type CardKind = 'animal' | 'job' | 'food' | 'object';

export interface WhoCard {
  /** The word printed on the card (lower case; the card prints it in capitals). */
  name: string;
  kind: CardKind;
  /** More accepted answers. */
  also?: readonly string[];
  /** Article for "Ticker guessed it: a penguin!" when not the usual a/an. */
  art?: 'a' | 'an' | '';
}

const A = (name: string, also?: string[], art?: WhoCard['art']): WhoCard => ({ name, kind: 'animal', ...(also ? { also } : {}), ...(art !== undefined ? { art } : {}) });
const J = (name: string, also?: string[], art?: WhoCard['art']): WhoCard => ({ name, kind: 'job', ...(also ? { also } : {}), ...(art !== undefined ? { art } : {}) });
const F = (name: string, also?: string[], art?: WhoCard['art']): WhoCard => ({ name, kind: 'food', ...(also ? { also } : {}), ...(art !== undefined ? { art } : {}) });
const O = (name: string, also?: string[], art?: WhoCard['art']): WhoCard => ({ name, kind: 'object', ...(also ? { also } : {}), ...(art !== undefined ? { art } : {}) });

